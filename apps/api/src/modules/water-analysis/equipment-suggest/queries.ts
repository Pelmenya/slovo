export const GENERIC_FALLBACK_QUERY = 'фильтр для очистки питьевой воды';

/**
 * Resolved targeted query для paramCode. Если paramCode нет в mapping —
 * fallback (используется когда регулируемый параметр оказался без specific
 * технологии).
 */
export function getTargetedQueryForParam(paramCode: string): string {
    return PROBLEM_TO_QUERY[paramCode] ?? GENERIC_FALLBACK_QUERY;
}
