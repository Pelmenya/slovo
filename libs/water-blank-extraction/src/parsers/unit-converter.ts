// Универсальные единицы для всех мг/л-параметров (метро-катионы, анионы,
// тяжёлые металлы): mostly «мг/л» во всех вариантах символа «/».
const MGL_PARAMS = new Set([
    'iron_total',
    'iron_2plus',
    'manganese',
    'magnesium',
    'calcium',
    'nitrates',
    'nitrites',
    'sulfates',
    'sulfides',
    'chlorides',
    'fluorides',
    'hydrogen_sulfide',
    'ammonium',
]);

const MGL_NORMALIZER: Record<string, string> = {
    'мг/л': 'мг/л',
    'мг/дм³': 'мг/л',
    'мг/дм3': 'мг/л',
    'mg/l': 'мг/л',
};

// Щёлочность — отдельная единица
const ALKALINITY_NORMALIZER: Record<string, string> = {
    'мг-экв/л': 'мг-экв/л',
    'ммоль/л': 'мг-экв/л',
    'мгэкв/л': 'мг-экв/л',
};

/**
 * Нормализует unitRaw в каноническую форму для заданного paramCode.
 *
 * @returns каноническая единица или `null` если unitRaw не распознан для этого параметра
 *          (вызывающий код может помечать запись paramFlags['unit_mismatch'])
 */
export function normalizeUnit(paramCode: string, unitRaw: string | null | undefined): string | null {
    if (paramCode === 'alkalinity_total') {
        return lookupUnit(ALKALINITY_NORMALIZER, unitRaw);
    }
    if (MGL_PARAMS.has(paramCode)) {
        return lookupUnit(MGL_NORMALIZER, unitRaw);
    }
    const map = CANONICAL_UNITS[paramCode];
    if (!map) return null;
    return lookupUnit(map, unitRaw);
}

function lookupUnit(map: Record<string, string>, raw: string | null | undefined): string | null {
    if (raw === null || raw === undefined) {
        // pH допускает empty unit
        return map[''] ?? null;
    }
    // NBSP (U+00A0) сначала на обычный пробел, затем collapse + lowercase + trim.
    // Раньше регекс был /\xA0/ vs / / — оба ' ' одинаковые при копировании,
    // что делало NBSP-замену no-op (зафиксировано ревью 2026-05-06).
    const cleaned = raw.replace(/\u00A0/g, ' ')
        .trim()
        .toLowerCase()
        .replace(/\s+/g, ' ');
    return map[cleaned] ?? null;
}
