// Нормализация единиц измерения параметров водного анализа.
//
// Из dataset (15 504 бланков) выявлены OCR-вариации одной и той же единицы:
//   - Температура: «°C» (latin) ≡ «°С» (cyrillic) — 100% совпадение semantically
//   - Жёсткость: «мг-экв/л» (99.8%), «мг/л» (0.17%), «м2-экв/л» (OCR опечатка)
//   - Окисляемость: «мгО₂/л» ≡ «мг О₂/л» ≡ «мгО/л» — три варианта одного
//   - Цветность: «градусы» (98.5%) ≡ «град» (1.5%)
//   - Запах: «баллы» (99.96%) ≡ «балл» ≡ «балла»
//   - Электропроводность: «мкСм/см» (95%), «мг-экв/л» (OCR — wrong unit), «мкО/л» / «мкОм/л» (OCR)
//   - Мутность: «ЕМФ» (98.5%), «мг/л» (0.5% — другая методика, каолин), «ед.мутности» / «ед.» (sinонимы)
//
// Стратегия: нормализатор для каждого paramCode держит карту допустимых
// синонимов unit → каноническая форма. Если unit не распознан — возвращаем
// `null` (вызывающий код помечает paramFlags['unit_mismatch']).

